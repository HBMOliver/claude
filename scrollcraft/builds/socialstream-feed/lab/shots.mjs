// node feed2-shots.mjs <outdir> <w> <h> [m]   (run from a folder with playwright-core)
import { createRequire } from 'node:module';
const { chromium } = createRequire(process.cwd() + '/')('playwright-core');
const [out, W, H, mob] = [process.argv[2], +process.argv[3], +process.argv[4], process.argv[5] === 'm'];
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const ctx = await b.newContext(mob ? { viewport: { width: W, height: H }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 } : { viewport: { width: W, height: H } });
const p = await ctx.newPage(); const errs = []; const res = {};
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('http://localhost:4541/', { waitUntil: 'load' }); await p.waitForTimeout(2500);
let i = 0; const shot = async (n) => p.screenshot({ path: `${out}/${String(i++).padStart(2, '0')}-${n}.png` });
const go = async (id, wait = 1600) => { await p.evaluate(id => document.getElementById(id).scrollIntoView({ behavior: 'instant' }), id); await p.waitForTimeout(wait); };
if (!mob) await p.mouse.move(W * 0.7, H * 0.3);
await shot('film');
await go('p2', 3600); await shot('law1');
await go('p3', 4200); await shot('law2');
await go('p4', 3400); await shot('law3');
await go('p5', 1800); await shot('svc');
await p.evaluate(() => { const c = document.querySelector('#p5 .car'); c.scrollTo({ left: c.clientWidth * 4, behavior: 'instant' }); }); await p.waitForTimeout(1600); await shot('svc5');
await go('p6', 1800); await shot('res');
await p.locator('#openComments').click(); await p.waitForTimeout(800); await shot('sheet');
await p.locator('#closeSheet').click(); await p.waitForTimeout(500);
await go('p7', 1600); await shot('reviews');
await go('p8', 1600); await shot('team');
await p.locator('[data-story="1"]').click(); await p.waitForTimeout(900); await shot('story');
await p.locator('#storyClose').click({ force: true });
await go('p9', 900); await p.locator('.opt[data-ans="yes"]').click(); await p.waitForTimeout(600); await shot('poll');
await go('p10', 2200); await p.fill('#reply', 'Teszt Elek'); await p.press('#reply', 'Enter'); await p.waitForTimeout(1600); await shot('dm');
res.dm = await p.evaluate(() => [...document.querySelectorAll('#thread .msg')].map(m => m.textContent.slice(0, 40)));
await p.evaluate(() => document.querySelector('.foot').scrollIntoView({ behavior: 'instant' })); await p.waitForTimeout(900); await shot('foot');
await p.locator('[data-set-lang="en"]').first().click(); await p.waitForTimeout(400); await go('p3', 4000); await shot('en-law2');
res.field = await p.evaluate(() => document.body.dataset.field);
res.overflow = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth);
res.errs = errs;
console.log(JSON.stringify(res));
await b.close();
