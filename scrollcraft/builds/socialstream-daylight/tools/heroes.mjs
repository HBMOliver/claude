// node tools/heroes.mjs
// Write hero-cinema.html, hero-glow.html and hero-capsule.html next to index.html: the same page with
// its first screen swapped for heroes/<name>.html, plus heroes.css and heroes.js. Edit heroes/*.html,
// not the generated pages. index.html itself keeps the original first screen.
import fs from 'node:fs';
function swap(s, from, to) { if (!s.includes(from)) throw new Error('not found: ' + from); return s.replace(from, () => to); }
const src = fs.readFileSync('index.html', 'utf8');
const a = src.indexOf('  <!-- the first screen'), b = src.indexOf('  <!-- the number -->');
if (a < 0 || b < a) throw new Error('the first screen was not found in index.html');
for (const name of ['cinema', 'glow', 'capsule']) {
  let out = src.slice(0, a) + fs.readFileSync(`heroes/${name}.html`, 'utf8').trimEnd() + '\n\n' + src.slice(b);
  out = swap(out, '<link rel="stylesheet" href="daylight.css">', '<link rel="stylesheet" href="daylight.css">\n<link rel="stylesheet" href="heroes.css">');
  out = swap(out, '<script src="daylight.js"></script>', '<script src="daylight.js"></script>\n<script src="heroes.js"></script>');
  out = swap(out, '<html lang="hu">', `<!-- generated by tools/heroes.mjs from index.html and heroes/${name}.html -->\n<html lang="hu">`);
  fs.writeFileSync(`hero-${name}.html`, out);
  console.log(`hero-${name}.html`, out.length, 'bytes');
}
